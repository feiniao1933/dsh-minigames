/**
 * Build the Client bundle for the DSH mini-games plugin.
 *
 * The browser artifact is a single hand-authored script that registers one
 * lazy factory on `window.__ModuleLoader__`. Node serves exactly the file the
 * package's `./client` export names, so the bundle cannot import sibling ESM
 * files at runtime. The sources are therefore kept as plain ESM under `src/`
 * (testable directly in Node) and deterministically concatenated here:
 * module-level `import`/`export` syntax is stripped and both files share one
 * function scope inside the registered factory.
 *
 * Usage:
 *   node build.mjs              # write ./client.js (production bundle)
 *   node build.mjs --test       # write ./smoke/.client.test-build.js with internals
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = dirname(fileURLToPath(import.meta.url));
const manifest = JSON.parse(readFileSync(join(ROOT, 'package.json'), 'utf8'));
if (typeof manifest.name !== 'string' || manifest.name.length === 0) {
  throw new Error('package.json is missing a package name');
}
if (manifest.dsh?.client?.platform !== 'web') {
  throw new Error('package.json dsh.client.platform must be "web"');
}
if (manifest.exports?.['./client'] !== './client.js') {
  throw new Error('package.json exports["./client"] must be "./client.js"');
}
const PACKAGE_NAME = manifest.name;
const testBuild = process.argv.includes('--test');

/** Read one source file relative to the package root. */
function read(relPath) {
  return readFileSync(join(ROOT, relPath), 'utf8');
}

/**
 * Strip module-level import/export syntax so the file becomes plain statements.
 * Only the authored subset is accepted: `import ... from '...'` (single line),
 * `export const|let|var|function|class`. Anything else export-shaped throws so a
 * future edit cannot silently produce a broken bundle.
 */
function stripModuleSyntax(relPath) {
  const source = read(relPath);
  const lines = source.split('\n');
  const out = [];
  for (let i = 0; i < lines.length; i += 1) {
    const line = lines[i];
    const trimmed = line.trimStart();
    const indent = line.slice(0, line.length - trimmed.length);
    if (/^import\s/.test(trimmed)) {
      if (!/^import\s[^;]*from\s+['"][^'"]+['"];?$/.test(trimmed)) {
        throw new Error(`${relPath}:${i + 1}: only single-line "import ... from '...'" is supported`);
      }
      continue;
    }
    if (/^export\s*\*/.test(trimmed) || /^export\s*\{/.test(trimmed)) {
      throw new Error(`${relPath}:${i + 1}: export lists/re-exports are not supported; use export declarations`);
    }
    if (/^export\s+default\b/.test(trimmed)) {
      throw new Error(`${relPath}:${i + 1}: default exports are not supported`);
    }
    const declaration = trimmed.match(/^export\s+(?:async\s+)?(?:const|let|var|function|class)\b/);
    if (declaration) {
      out.push(indent + trimmed.slice('export '.length));
      continue;
    }
    if (/^export\b/.test(trimmed)) {
      throw new Error(`${relPath}:${i + 1}: unsupported export form: ${trimmed}`);
    }
    out.push(line);
  }
  return out.join('\n');
}

const engineSource = stripModuleSyntax('src/engine.js');
const uiSource = stripModuleSyntax('src/ui.js');

function indent(text) {
  return text
    .split('\n')
    .map((line) => (line.length === 0 ? line : `    ${line}`))
    .join('\n');
}

const testExport = testBuild
  ? `    return { inject: inject, apply: apply, __test: __mgTestExports };`
  : `    return { inject: inject, apply: apply };`;

const bundle = `/* dsh-minigames client bundle: generated by build.mjs; do not edit directly. */
window.__ModuleLoader__.load({
  id: '${PACKAGE_NAME}',
  factory(require) {
    const React = require('react');

${indent(engineSource)}
${indent(uiSource)}
${testExport}
  },
});
`;

const target = testBuild ? 'smoke/.client.test-build.js' : 'client.js';
mkdirSync(dirname(join(ROOT, target)), { recursive: true });
writeFileSync(join(ROOT, target), bundle);
process.stdout.write(`wrote ${target} (${bundle.length} bytes)\n`);
